// Install PGlite outside the repository and pass its absolute module path.
// This fixture never connects to Supabase or calls a publishing API.
import { pathToFileURL, fileURLToPath } from 'node:url';
if (!process.env.PGLITE_MODULE) throw new Error('Set PGLITE_MODULE to an externally installed @electric-sql/pglite module path.');
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
import { readFile } from 'node:fs/promises';
export const root=fileURLToPath(new URL('../../',import.meta.url)).replace(/\/$/,'');
export async function createFixture(){
  const db=new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth;
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  create table public.os_profiles(id uuid primary key,is_active boolean not null default true,role text not null default 'member');`);
  const baseline=await readFile(root+'/supabase/migrations/20260917082749_core_baseline.sql','utf8');
  await db.exec(baseline.match(/CREATE TABLE IF NOT EXISTS "public"\."os_records" \([\s\S]*?\n\);/)[0]);
  await db.exec('alter table public.os_records add primary key(id)');
  await db.exec(baseline.match(/CREATE OR REPLACE FUNCTION "public"\."os_records_before_write"\(\)[\s\S]*?\n\$\$;/)[0]);
  await db.exec(`create trigger os_records_before_write before insert or update on public.os_records for each row execute function public.os_records_before_write();`);
  await db.exec(baseline.match(/CREATE TABLE IF NOT EXISTS "public"\."os_record_events" \([\s\S]*?\n\);/)[0]);
  await db.exec('alter table public.os_record_events alter column id add generated by default as identity');
  await db.exec(baseline.match(/CREATE OR REPLACE FUNCTION "public"\."os_records_after_write"\(\)[\s\S]*?\n\$\$;/)[0]);
  await db.exec('create trigger os_records_after_write after insert or update on public.os_records for each row execute function public.os_records_after_write()');
  const meta=await readFile(root+'/supabase/migrations/20261003044602_final_os_channel_connections.sql','utf8');
  await db.exec(meta.match(/create table if not exists public\.os_meta_connections \([\s\S]*?\n\);/)[0]);
  const automation=await readFile(root+'/supabase/migrations/20261011003653_content_automation_v07.sql','utf8');
  for(const name of ['os_publication_events','os_content_review_log']) {
    const block=automation.match(new RegExp('create table public\\.'+name+' \\([\\s\\S]*?\\n\\);'))?.[0];
    if(!block)throw Error(name);
    await db.exec(block);
  }
  await db.exec(`grant usage on schema public,auth to service_role,authenticated,anon;
  grant all on all tables in schema public to service_role; grant usage,select on all sequences in schema public to service_role;
  grant select,update,delete,insert on public.os_records to authenticated;
  create function public.os_is_content_reviewer(p_actor uuid) returns boolean language sql stable as $$ select exists(select 1 from public.os_profiles where id=p_actor and is_active) $$;`);
  return db;
}
