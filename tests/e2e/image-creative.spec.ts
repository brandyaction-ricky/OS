  await page.getByText("구독 AI 결과 직접 가져오기").click();
  await approveFormat(page);
  await page.getByLabel("결과 JSON").fill(JSON.stringify({variants:[{formatId:"typography",formatVersion:1,size:"portrait",appeal:{id:"one",meaning:"업무 상황 이해"},copy:{headline:"일이 자꾸 미뤄진다면",body:"시작이 어려운 순간",cta:"자세히 보기"}}]}));
  await page.getByRole("button",{name:"결과 가져오기"}).click();
  await finishDemoBatch(page,1);
  await page.getByRole("button",{name:"기준 시안 선택",exact:true}).click();
  await page.reload();
  await page.getByLabel("기존 작업").selectOption({label:"광고 테스트"});
  await expect(page.getByRole("button",{name:"기준으로 선택됨"})).toBeVisible();
  await page.getByRole("button",{name:/소구점 비교/}).click();
  await expect(page.getByText("기준 시안: 일이 자꾸 미뤄진다면")).toBeVisible();
  await page.getByLabel("후보 수").fill("1");
  await page.getByText("구독 AI 결과 직접 가져오기").click();
  await approveFormat(page);
  await page.getByLabel("결과 JSON").fill(JSON.stringify({variants:[{appeal:{id:"two",meaning:"계속 미루는 상황 공감"},copy:{headline:"시작만 하면 멈춘다면",body:"익숙한 업무 속 장면",cta:"자세히 보기"}}]}));
  await page.getByRole("button",{name:"결과 가져오기"}).click();
  await finishDemoBatch(page,2);
  const appealCard=page.locator("article").filter({has:page.getByRole("heading",{name:"시작만 하면 멈춘다면"})});
  await appealCard.getByRole("button",{name:"기준 시안 선택"}).click();
  await page.getByRole("button",{name:/카피 비교/}).click();
